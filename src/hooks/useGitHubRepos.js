import { useState, useEffect } from 'react';
import { GITHUB_USERNAME, GITHUB_PAGES_HOST } from '../utils/githubShared.js';

const CACHE_KEY = `gh_repos_${GITHUB_USERNAME}`;
const CACHE_TTL = 15 * 60 * 1000; // 15 minutes

/* How long the function gets before we give up and use the snapshot. */
const API_TIMEOUT_MS = 6000;

/**
 * Fetches all public repos for a GitHub user.
 * - On GitHub Pages (mhtamim136.github.io): loads the build-time
 *   snapshot `public/projects.json` directly — /api/projects is never
 *   attempted there, because no function exists on a static host.
 * - Everywhere else (Vercel, localhost): tries the serverless
 *   function `GET /api/projects` first (server-side token, fresh
 *   data, no browser rate limit), and falls back to the snapshot on
 *   any failure (non-OK, network error, timeout). The fallback is
 *   never executed on Vercel while the function answers.
 * - There is NO direct browser call to api.github.com anymore — that
 *   was the path that hit the unauthenticated 60/hr limit (403) on
 *   shared IPs. The chain is now: function → snapshot only.
 * - Function results are cached in sessionStorage with a TTL (the
 *   snapshot path keeps its old behaviour of not writing the cache).
 *
 * Both sources now also carry `featured` — the first 4 pinned repos
 * (in pin order, excluding the portfolio site itself) — and each
 * featured repo carries a `details` object (see
 * scripts/featuredDetails.mjs). When `featured` is EMPTY (e.g. an
 * older snapshot, or the GraphQL pins query failed), the Projects
 * section degrades gracefully to the all-projects grid. A cached
 * payload in the OLD shape (a bare repos array, written before
 * Featured existed) is NOT applied — it is a cache miss and the
 * hook fetches fresh data, so a stale tab can never hide Featured.
 *
 * Returns { repos, featured, loading, error }.
 */
export function useGitHubRepos() {
  const [repos, setRepos] = useState([]);
  const [featured, setFeatured] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const controller = new AbortController();

    /* A payload is usable ONLY in the new shape: an object with a
       non-empty `repos` array AND a `featured` array. The check is
       on the SHAPE, not on emptiness — a legitimately empty
       `featured` (e.g. the GraphQL pins query failed) is a valid
       payload and renders the old grid on purpose.
       The old code cached a BARE repos array under the same key;
       tolerating that shape made the new bundle render the old grid
       for up to 15 minutes (sessionStorage survives reloads), so an
       old-shape entry is now a cache MISS and the hook fetches fresh
       data instead. All non-cache callers already normalise
       `featured` to an array (see loadSnapshot / the function branch
       below), so this rule changes nothing for them. */
    function applyData(data) {
      if (!data || Array.isArray(data)) return false;
      if (!Array.isArray(data.repos) || data.repos.length === 0) return false;
      if (!Array.isArray(data.featured)) return false;
      setRepos(data.repos);
      setFeatured(data.featured);
      return true;
    }

    async function fetchRepos() {
      /* ── Check cache first ── */
      try {
        const cached = sessionStorage.getItem(CACHE_KEY);
        if (cached) {
          const { data, timestamp } = JSON.parse(cached);
          if (Date.now() - timestamp < CACHE_TTL && applyData(data)) {
            setLoading(false);
            return;
          }
        }
      } catch {
        /* corrupt cache — ignore */
      }

      /* ── Load the build-time snapshot (public/projects.json).
         Generated by `npm run fetch-projects` / `prebuild`, so the
         site normally makes ZERO GitHub API calls. ── */
      async function loadSnapshot() {
        const res = await fetch('/projects.json', { signal: controller.signal });
        if (!res.ok) return null;
        const snapshot = await res.json();
        if (Array.isArray(snapshot.repos) && snapshot.repos.length > 0) {
          return {
            repos: snapshot.repos,
            featured: Array.isArray(snapshot.featured) ? snapshot.featured : [],
          };
        }
        return null;
      }

      /* ── GitHub Pages: snapshot only, never /api/projects. ── */
      if (window.location.hostname === GITHUB_PAGES_HOST) {
        try {
          const snapshot = await loadSnapshot();
          if (snapshot) {
            applyData(snapshot);
          } else {
            setError('Projects could not be loaded. Please try again later.');
          }
        } catch (err) {
          if (err.name !== 'AbortError') {
            setError('Projects could not be loaded. Please try again later.');
          }
        } finally {
          setLoading(false);
        }
        return;
      }

      /* ── Elsewhere: function first, snapshot fallback. ── */
      try {
        let data = null;
        let fromFunction = false;

        let timerId;
        try {
          const timeout = new Promise((_, reject) => {
            timerId = setTimeout(
              () => reject(new Error('Function timeout')),
              API_TIMEOUT_MS,
            );
          });
          const res = await Promise.race([
            fetch('/api/projects', { signal: controller.signal }),
            timeout,
          ]);
          clearTimeout(timerId);
          if (res.ok) {
            const payload = await res.json();
            if (Array.isArray(payload.repos) && payload.repos.length > 0) {
              data = {
                repos: payload.repos,
                featured: Array.isArray(payload.featured) ? payload.featured : [],
              };
              fromFunction = true;
            }
          }
        } catch {
          /* Function unavailable — fall through to the snapshot. */
          clearTimeout(timerId);
        }

        if (!data) {
          data = await loadSnapshot();
        }

        if (data) {
          /* Cache function results (as the old live-API path did);
             snapshot results keep the old no-cache behaviour. */
          if (fromFunction) {
            try {
              sessionStorage.setItem(
                CACHE_KEY,
                JSON.stringify({ data, timestamp: Date.now() }),
              );
            } catch {
              /* sessionStorage full or unavailable — non-critical */
            }
          }
          applyData(data);
        } else {
          setError('Projects could not be loaded. Please try again later.');
        }
      } catch (err) {
        if (err.name !== 'AbortError') {
          setError('Projects could not be loaded. Please try again later.');
        }
      } finally {
        setLoading(false);
      }
    }

    fetchRepos();
    return () => controller.abort();
  }, []);

  return { repos, featured, loading, error };
}
